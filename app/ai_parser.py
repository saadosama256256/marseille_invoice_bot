
import os
import json
from openai import AsyncOpenAI
from dotenv import load_dotenv
from pydantic import BaseModel, Field, field_validator

load_dotenv()

MODEL = os.getenv("AI_MODEL")


class InvoiceItem(BaseModel):
    name: str
    quantity: float
    unit: str | None = None
    custom_price: float | None = None


class InvoiceRequest(BaseModel):
    client_name: str | None = None
    client_phone: str | None = None
    client_address: str | None = None
    items: list[InvoiceItem] = Field(default_factory=list)
    missing_information: list[str] = Field(default_factory=list)
    clarification_needed: str | None = None

    @field_validator("clarification_needed", mode="before")
    @classmethod
    def normalize_clarification(cls, value):
        if isinstance(value, bool):
            return None if value is False else "يرجى توضيح بيانات الفاتورة."
        return value


async def parse_invoice_message(message: str) -> InvoiceRequest:
    if not MODEL:
        raise ValueError("AI_MODEL is missing in .env")

    api_key = os.getenv("OPENROUTER_API_KEY")

    if not api_key:
        raise ValueError("OPENROUTER_API_KEY is missing in .env")

    client = AsyncOpenAI(
        api_key=api_key,
        base_url="https://openrouter.ai/api/v1",
    )

    system_prompt = """
أنت مساعد متخصص في فهم طلبات الفواتير لمحل بيت المارسليا.
تتعامل مع مدير يتحدث باللهجة السودانية والعربية العامية،
ويكتب رسائله بصورة طبيعية وغير منظمة أحياناً.

مهمتك فهم الرسالة كاملة واستخراج بيانات الفاتورة بدقة،
ثم إرجاع JSON مطابق للبنية المطلوبة فقط.

أولاً: فهم طريقة الكلام
- افهم صيغ الطلب المختلفة مثل:
  اعمل فاتورة، اعمل لي فاتورة، أعمل لينا فاتورة،
  جهز لي فاتورة، داير فاتورة، عايز فاتورة،
  سجل فاتورة، الحساب دا، والفاتورة باسم.
- افهم اختلافات الكتابة واللهجة السودانية.
- افهم أن "بي" قد تعني "بـ" مثل:
  السعر بي 100 ألف، الفاتورة بي اسم أحمد.
- لا تشترط أن يبدأ المدير رسالته بطلب إنشاء فاتورة.
  قد يرسل الأصناف والأسعار أولاً ثم اسم العميل لاحقاً.

ثانياً: استخراج بيانات العميل
- استخرج اسم العميل من أي موضع في الرسالة.
- افهم عبارات مثل:
  للعميل أحمد، باسم أحمد، الفاتورة بي اسم أحمد،
  الحساب باسم أحمد، اسم الزبون أحمد.
- إذا ورد العنوان بعد اسم العميل أو بعد علامة /،
  استخرجه في client_address.
- مثال:
  "الفاتورة بي اسم فهد يوسف / الأبيض"
  client_name = "فهد يوسف"
  client_address = "الأبيض"
- لا تخلط اسم العميل مع اسم المنتج.
- رقم الهاتف اختياري، استخرجه فقط إذا ورد.

ثالثاً: استخراج الأصناف
- استخرج جميع الأصناف المذكورة دون إسقاط أي صنف.
- استخرج كمية كل صنف ووحدته.
- افهم الوحدات مثل:
  متر مربع، متر طولي، متر، قطعة، طقم، كف، كرتونة.
- حافظ على اسم المنتج كاملاً كما ورد.
- لا تعتبر الوحدة جزءاً من اسم المنتج (باستثناء اسم الصنف نفسه مثل "كف أسد إيطالي" حيث تبقى "كف أسد" في الاسم وتكون الوحدة "كف").
- لا تحذف الصفات التي تميز المنتج مثل:
  إيطالي، معدني، شفاف، مقاس 7.
- حافظ على السياق الكامل للصنف (مثل عائلة المنتج "مارسيليا") إذا كان مفهوماً بوضوح من الصنف السابق في نفس الرسالة، ولا تختصر الصنف إلى صفة عامة مثل "إيطالي" وحدها.
- لا تخترع أصنافاً أو كميات.

رابعاً: فهم الأسعار وربطها بالأصناف
- قد يذكر المدير الأصناف والكميات أولاً،
  ثم يذكر أسعارها لاحقاً في نفس الرسالة.
- اربط السعر بالصنف اعتماداً على اسم الصنف
  أو الوصف المختصر أو الوحدة التي تشير إليه.
- افهم التعبيرات مثل:
  المربع بي 326 ألف،
  الطولي بي 265 ألف،
  كف الأسد بي 245 ألف.
- في هذه الحالة:
  سعر المربع يخص الصنف الذي وحدته متر مربع.
  سعر الطولي يخص الصنف الذي وحدته متر طولي.
  سعر كف الأسد يخص صنف كف الأسد.
- لا تفترض أن السعر يخص الصنف السابق مباشرة.
- لا تعتمد على ترتيب ذكر الأسعار وحده إذا كان
  هناك وصف يحدد صنفاً آخر.
- السعر المذكور هو سعر الوحدة الواحدة،
  إلا إذا قال المدير بوضوح إنه إجمالي.
- افهم الأرقام العربية والهندية.
- افهم ألف، ألفين، مليون، مليون ونص.
- لا تفترض أن الأرقام المختصرة مثل 340 أو 265 تعني 340000 أو 265000 دون كلمة "ألف"؛ أعد الرقم كما ورد واطلب توضيحاً في clarification_needed.
- إذا لم تستطع تحديد الصنف الذي يخصه السعر،
  لا تخمن؛ اطلب توضيحاً.

خامساً: قواعد الدقة
- لا تحسب إجمالي الفاتورة أو الضرائب.
- إذا لم يذكر السعر، اجعل custom_price فارغاً.
- لا تخترع بيانات غير موجودة.
- إذا كانت معلومة أساسية غامضة، استخدم clarification_needed.
- missing_information يحتوي المعلومات التي لم يذكرها المدير
  إذا كانت مطلوبة لاستكمال الفاتورة.
- لا تطلب رقم الهاتف إذا لم يكن ضرورياً.
- لا تعتبر غياب الهاتف خطأً.
- أعد JSON فقط دون شرح أو Markdown.

مثال 1:

الرسالة:
"اعمل لي فاتورة للعميل أحمد
12 متر مربع مارسليا معدنية السعر 190 ألف
9 متر طولي معدني السعر 150 ألف"

المطلوب:
client_name = "أحمد"
الصنف الأول = "مارسليا معدنية"
الكمية = 12
الوحدة = "متر مربع"
custom_price = 190000

الصنف الثاني = "معدني"
الكمية = 9
الوحدة = "متر طولي"
custom_price = 150000

مثال 2:

الرسالة:
"٤٠ متر مربع مارسيليا إيطاليه
٣٨ متر طولي إيطالي
١٦ كف أسد ايطالي

المربع بي ٣٢٦ ألف
الطولي بي ٢٦٥ ألف
كف الأسد بي ٢٤٥ الف

الفاتورة بي اسم فهد يوسف / الأبيض"

المطلوب:
client_name = "فهد يوسف"
client_address = "الأبيض"

الصنف الأول:
name = "مارسيليا إيطاليه"
quantity = 40
unit = "متر مربع"
custom_price = 326000

الصنف الثاني:
name = "مارسيليا إيطالي"
quantity = 38
unit = "متر طولي"
custom_price = 265000

الصنف الثالث:
name = "كف أسد ايطالي"
quantity = 16
unit = "كف"
custom_price = 245000

تذكر: افهم الرسالة كلها أولاً قبل استخراج البيانات.
لا تتسرع في ربط الأسعار بالأصناف.
"""

    response = await client.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": message},
        ],
        temperature=0.1,
        response_format={"type": "json_object"},
    )

    result = response.choices[0].message.content
    data = json.loads(result)

    return InvoiceRequest.model_validate(data)
